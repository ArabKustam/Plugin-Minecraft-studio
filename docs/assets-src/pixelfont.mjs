const ALIAS = { А: 'A', В: 'B', Е: 'E', К: 'K', М: 'M', Н: 'H', О: 'O', Р: 'P', С: 'C', Т: 'T', Х: 'X' };

export function glyph(ch) {
  const c = ch.toUpperCase();
  const g = G[c] || G[ALIAS[c]];
  if (!g) throw new Error(`pixel font: no glyph for "${ch}" (U+${ch.codePointAt(0).toString(16)})`);
  return g;
}

/** Width in font pixels (before scaling) of a string. */
export function measure(text, spacing = 1) {
  return [...text].reduce((w, ch, i) => w + glyph(ch)[0].length + (i ? spacing : 0), 0);
}

/** Draw text with a callback px(x, y) per lit font pixel (unscaled coordinates). */
export function layout(text, spacing = 1) {
  const pixels = [];
  let x = 0;
  for (const ch of text) {
    const g = glyph(ch);
    g.forEach((row, y) => [...row].forEach((c, dx) => { if (c === '#') pixels.push([x + dx, y]); }));
    x += g[0].length + spacing;
  }
  return { pixels, width: Math.max(0, x - spacing), height: 7 };
}
